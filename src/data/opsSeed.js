export function money(value) {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 2,
  }).format(value)
}

export function maskSensitive(value, visibleStart = 2, visibleEnd = 2) {
  if (!value || value.length <= visibleStart + visibleEnd) {
    return value
  }

  const start = value.slice(0, visibleStart)
  const end = value.slice(value.length - visibleEnd)
  return `${start}${"*".repeat(value.length - (visibleStart + visibleEnd))}${end}`
}
